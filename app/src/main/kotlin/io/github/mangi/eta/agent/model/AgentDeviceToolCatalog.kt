    private fun searchFunction(name: String, description: String): JSONObject =
        function(
            name,
            description,
            if (name in setOf("search_notes", "search_system_memories", "search_calendar_events", "search_media", "search_files")) {
                AgentPersonalSearchToolCatalog.searchProperties().also { properties ->
                    if (name == "search_notes") properties.put("current_only", boolean("тількизробитивикористовуватиколивпередОригіналпочатокзручнийзнакприходьджерело，немаєповерненнявідступкалендарісторіїОтжепривести"))
                    if (name in setOf("search_media", "search_files")) properties.put("match", enumString("name перевіритиколивпередмистецтваштукназва；content перевіритикалендарісторіїВсерединіДозволитиОтжепривести", "name", "content"))
                }
            } else properties("query" to string("можевибратизакритиключслово，більшістьбагато 200 характер", 200), "limit" to integer("більшістьбагатоповерненняповерненняномеркількість，мовчазнийрозпізнати 10", 1, 30)),
        )

    private fun function(
        name: String,
        description: String,
        properties: JSONObject,
        vararg required: String,
    ): JSONObject =
        AgentToolSchema.function(
            name = name,
            description = description,
            parameters = JSONObject()
                .put("type", "object")
                .put("properties", properties)
                .also { schema ->
                    if (required.isNotEmpty()) schema.put("required", JSONArray(required.toList()))
                },
        )

    private fun properties(vararg entries: Pair<String, JSONObject>): JSONObject =
        JSONObject().also { target -> entries.forEach { (name, schema) -> target.put(name, schema) } }

    private fun string(description: String, maxLength: Int? = null): JSONObject =
        JSONObject()
            .put("type", "string")
            .put("description", description)
            .also { schema -> maxLength?.let { schema.put("maxLength", it) } }

    private fun boolean(description: String): JSONObject =
        JSONObject().put("type", "boolean").put("description", description)

    private fun userId(): JSONObject =
        integer("Android використовуватипобутовікомпілюватиНомер，мовчазнийрозпізнати Eta Місцерідвикористовуватипобутові；щовінвикористовуватипобутовіабопрацюватиробитиКапіталматеріалповерненняповернення USER_SCOPE_UNSUPPORTED", 0, Int.MAX_VALUE)

    private fun integer(description: String, minimum: Int, maximum: Int): JSONObject =
        JSONObject()
            .put("type", "integer")
            .put("minimum", minimum)
            .put("maximum", maximum)
            .put("description", description)

    private fun enumString(description: String, vararg values: String): JSONObject =
        string(description).put("enum", JSONArray(values.toList()))

    private fun stringArray(description: String, vararg values: String): JSONObject =
        JSONObject()
            .put("type", "array")
            .put("items", enumString(description, *values))
            .put("uniqueItems", true)
            .put("maxItems", 7)
            .put("description", description)
