        function(name, description, properties())

    private fun limitFunction(name: String, description: String): JSONObject =
        function(
            name,
            description,
            properties("limit" to integer("більшістьбагатоповерненняповерненняномеркількість，мовчазнийрозпізнати 10", 1, 30)),
